  DrawPattern(&sheet, ENEMY_BULLETS_DATA[0][0], 8, 1, 1, RED);
  DrawPattern(&sheet, ENEMY_BULLETS_DATA[0][1], 8, 2, 1, RED);
  DrawPattern(&sheet, ENEMY_BULLETS_DATA[1][0], 8, 3, 1, RED);
