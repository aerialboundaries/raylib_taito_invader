  DrawPattern(&sheet, PLAYER_EXPLOSION_DATA[0], 8, 1, 2, GREEN);
  DrawPattern(&sheet, PLAYER_EXPLOSION_DATA[1], 8, 2, 2, GREEN);
  DrawPattern(&sheet, BUNKER_DATA, 16, 3, 2, GREEN);

